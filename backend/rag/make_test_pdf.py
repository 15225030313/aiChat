"""生成一份中文测试 PDF，模拟用户上传的企业制度文档"""
import fitz  # pymupdf 的 import 名

pages_text = [
    """第一章 总则
第一条 为规范公司差旅及日常费用报销管理，特制定本制度。
第二条 本制度适用于全体正式员工及实习生。

第二章 交通费报销
第三条 员工市内出行优先选择地铁、公交；打车费需说明事由并经部门主管审批。
第四条 城际差旅高铁二等座可全额报销，飞机经济舱需提前三天申请。

第三章 餐费与住宿
第五条 工作日加班至 21 点后可报销晚餐，上限 40 元。
第六条 出差住宿标准：一线城市每晚 500 元，其他城市 350 元。""",
    """第四章 报销流程
第七条 员工须在费用发生后 30 天内，在 OA 系统提交报销单并上传发票照片。
第八条 发票要求：抬头为公司全称，税号正确，发票金额与消费一致。
第九条 审批流转：部门主管 → 财务初审 → 总经理审批（单笔超 5000 元）→ 出纳打款。

第五章 附则
第十条 虚假报销一经查实，追回款项并按公司奖惩制度处理。
第十一条 本制度自 2026 年 1 月 1 日起施行，由财务部负责解释。""",
]

doc = fitz.open()
for text in pages_text:
    page = doc.new_page()
    # china-s 是 pymupdf 内置简体中文字体
    page.insert_text((50, 72), text, fontname="china-s", fontsize=11)

doc.save("test_data/公司报销制度.pdf")
print("已生成 test_data/公司报销制度.pdf，共", doc.page_count, "页")
